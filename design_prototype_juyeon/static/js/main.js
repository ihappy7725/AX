// =========================================================
// BUSINESS
// =========================================================

function activateBusiness(businessKey) {

    currentBusiness =
        businessKey;

    const data =
        translations[currentLanguage]
            .business[businessKey];

    if (!data) {
        return;
    }

    coreLabel.textContent =
        data.label;

    coreTitle.textContent =
        data.title;

    coreDescription.textContent =
        data.description;

    businessNodes.forEach((node) => {

        node.classList.toggle(
            "active",
            node.dataset.business ===
                businessKey
        );

    });

}


// =========================================================
// LANGUAGE
// =========================================================

function applyLanguage(language) {

    currentLanguage =
        language;

    localStorage.setItem(
        "axp-language",
        language
    );

    document.documentElement.lang =
        language === "zh"
            ? "zh-CN"
            : language;


    document
        .querySelectorAll("[data-i18n]")
        .forEach((element) => {

            const value =
                translations[language][
                    element.dataset.i18n
                ];

            if (value) {
                element.textContent =
                    value;
            }

        });


    document
        .querySelectorAll("[data-i18n-html]")
        .forEach((element) => {

            const value =
                translations[language][
                    element.dataset.i18nHtml
                ];

            if (value) {
                element.innerHTML =
                    value;
            }

        });


    currentLanguageLabel.textContent =
        languageLabels[language];

    desktopLanguage.textContent =
        languageLabels[language];

    activateBusiness(
        currentBusiness
    );

}


// =========================================================
// LANGUAGE MENU
// =========================================================

languageToggle.addEventListener(
    "click",
    (event) => {

        event.stopPropagation();

        languageMenu.classList.toggle(
            "open"
        );

    }
);


languageMenu
    .querySelectorAll("button")
    .forEach((button) => {

        button.addEventListener(
            "click",
            () => {

                applyLanguage(
                    button.dataset.language
                );

                languageMenu.classList.remove(
                    "open"
                );

            }
        );

    });


document.addEventListener(
    "click",
    () => {

        languageMenu.classList.remove(
            "open"
        );

    }
);


// =========================================================
// THEME
// =========================================================

function applyTheme(theme) {

    currentTheme =
        theme;

    document.documentElement.dataset.theme =
        theme;

    localStorage.setItem(
        "axp-theme",
        theme
    );

    themeIcon.textContent =
        theme === "dark"
            ? "☼"
            : "☾";

}


themeToggle.addEventListener(
    "click",
    () => {

        const nextTheme =
            currentTheme === "dark"
                ? "light"
                : "dark";

        applyTheme(
            nextTheme
        );

    }
);


