// CREATE REAL WORLD MAP TEXTURE
// 실제 국가 좌표 → Canvas → 3D Sphere Texture
// =========================================================

async function createWorldTexture(
    renderer
) {

    const canvas =
        document.createElement(
            "canvas"
        );

    canvas.width =
        2048;

    canvas.height =
        1024;


    const context =
        canvas.getContext("2d");


    // Ocean
    const oceanGradient =
        context.createLinearGradient(
            0,
            0,
            canvas.width,
            canvas.height
        );

    oceanGradient.addColorStop(
        0,
        "#123e5b"
    );

    oceanGradient.addColorStop(
        0.5,
        "#0b304b"
    );

    oceanGradient.addColorStop(
        1,
        "#071e31"
    );

    context.fillStyle =
        oceanGradient;

    context.fillRect(
        0,
        0,
        canvas.width,
        canvas.height
    );


    // =====================================================
    // Real world data
    // =====================================================

    const response =
        await fetch(
            "https://cdn.jsdelivr.net/npm/world-atlas@2/countries-110m.json"
        );

    const world =
        await response.json();


    const countries =
        topojson.feature(
            world,
            world.objects.countries
        );


    const borders =
        topojson.mesh(
            world,
            world.objects.countries,
            (a, b) => a !== b
        );


    // =====================================================
    // Equirectangular projection
    // =====================================================

    const projection =
        d3
            .geoEquirectangular()
            .fitExtent(
                [
                    [0, 0],
                    [
                        canvas.width,
                        canvas.height
                    ]
                ],
                {
                    type: "Sphere"
                }
            );


    const path =
        d3
            .geoPath(
                projection,
                context
            );


    // =====================================================
    // Longitude / latitude
    // =====================================================

    context.save();

    context.beginPath();

    path(
        d3.geoGraticule10()
    );

    context.strokeStyle =
        "rgba(197, 232, 250, 0.12)";

    context.lineWidth =
        1;

    context.stroke();

    context.restore();


    // =====================================================
    // Continents
    // =====================================================

    context.save();

    context.beginPath();

    path(
        countries
    );


    const landGradient =
        context.createLinearGradient(
            0,
            0,
            canvas.width,
            canvas.height
        );


    landGradient.addColorStop(
        0,
        "#e9f7ff"
    );

    landGradient.addColorStop(
        0.45,
        "#b7ddef"
    );

    landGradient.addColorStop(
        1,
        "#70aeca"
    );


    context.fillStyle =
        landGradient;

    context.fill();

    context.restore();


    // =====================================================
    // Country Borders
    // =====================================================

    context.save();

    context.beginPath();

    path(
        borders
    );

    context.strokeStyle =
        "rgba(255,255,255,0.42)";

    context.lineWidth =
        0.8;

    context.stroke();

    context.restore();


    // =====================================================
    // Soft light
    // =====================================================

    const glow =
        context.createRadialGradient(
            500,
            220,
            0,
            500,
            220,
            500
        );

    glow.addColorStop(
        0,
        "rgba(255,255,255,0.18)"
    );

    glow.addColorStop(
        1,
        "rgba(255,255,255,0)"
    );

    context.fillStyle =
        glow;

    context.fillRect(
        0,
        0,
        canvas.width,
        canvas.height
    );


    // =====================================================
    // Three Texture
    // =====================================================

    const texture =
        new THREE.CanvasTexture(
            canvas
        );

    texture.colorSpace =
        THREE.SRGBColorSpace;

    texture.anisotropy =
        renderer.capabilities
            .getMaxAnisotropy();

    texture.needsUpdate =
        true;

    return texture;

}


// =========================================================
// THREE.JS REAL EARTH
// =========================================================

async function initBusinessGlobe() {

    const container =
        document.getElementById(
            "businessGlobeCanvas"
        );


    if (
        !container ||
        typeof THREE === "undefined" ||
        typeof d3 === "undefined" ||
        typeof topojson === "undefined"
    ) {
        return;
    }


    const width =
        container.clientWidth;

    const height =
        container.clientHeight;


    // =====================================================
    // Scene
    // =====================================================

    const scene =
        new THREE.Scene();


    // =====================================================
    // Camera
    // =====================================================

    const camera =
        new THREE.PerspectiveCamera(
            34,
            width / height,
            0.1,
            100
        );


    camera.position.z =
        5.6;


    // =====================================================
    // Renderer
    // =====================================================

    const renderer =
        new THREE.WebGLRenderer({
            antialias: true,
            alpha: true
        });


    renderer.setPixelRatio(
        Math.min(
            window.devicePixelRatio,
            2
        )
    );


    renderer.setSize(
        width,
        height
    );


    renderer.outputColorSpace =
        THREE.SRGBColorSpace;


    container.innerHTML =
        "";


    container.appendChild(
        renderer.domElement
    );


    // =====================================================
    // Globe Group
    // =====================================================

    const globeGroup =
        new THREE.Group();


    scene.add(
        globeGroup
    );


    // =====================================================
    // Actual Map Texture
    // =====================================================

    let worldTexture;


    try {

        worldTexture =
            await createWorldTexture(
                renderer
            );

    }

    catch (error) {

        console.error(
            "World map loading failed:",
            error
        );

    }


    // =====================================================
    // Earth
    // =====================================================

    const sphereGeometry =
        new THREE.SphereGeometry(
            1.56,
            128,
            128
        );


    const earthMaterial =
        new THREE.MeshPhysicalMaterial({

            color:
                new THREE.Color(
                    "#d6efff"
                ),

            map:
                worldTexture || null,

            roughness:
                0.26,

            metalness:
                0.02,

            clearcoat:
                1,

            clearcoatRoughness:
                0.08,

            transmission:
                0.05,

            thickness:
                0.5

        });


    const earth =
        new THREE.Mesh(
            sphereGeometry,
            earthMaterial
        );


    globeGroup.add(
        earth
    );


    // =====================================================
    // Glass Shell
    // =====================================================

    const glassGeometry =
        new THREE.SphereGeometry(
            1.62,
            96,
            96
        );


    const glassMaterial =
        new THREE.MeshPhysicalMaterial({

            color:
                new THREE.Color(
                    "#bce7ff"
                ),

            transparent:
                true,

            opacity:
                0.09,

            roughness:
                0,

            transmission:
                0.60,

            clearcoat:
                1,

            side:
                THREE.FrontSide

        });


    const glassShell =
        new THREE.Mesh(
            glassGeometry,
            glassMaterial
        );


    globeGroup.add(
        glassShell
    );


    // =====================================================
    // Wireframe
    // =====================================================

    const wireGeometry =
        new THREE.SphereGeometry(
            1.585,
            32,
            20
        );


    const wireMaterial =
        new THREE.MeshBasicMaterial({

            color:
                new THREE.Color(
                    "#d6f2ff"
                ),

            wireframe:
                true,

            transparent:
                true,

            opacity:
                0.10

        });


    const wireSphere =
        new THREE.Mesh(
            wireGeometry,
            wireMaterial
        );


    globeGroup.add(
        wireSphere
    );


    // =====================================================
    // Atmosphere
    // =====================================================

    const atmosphereGeometry =
        new THREE.SphereGeometry(
            1.70,
            96,
            96
        );


    const atmosphereMaterial =
        new THREE.MeshBasicMaterial({

            color:
                new THREE.Color(
                    "#6cc9ff"
                ),

            transparent:
                true,

            opacity:
                0.065,

            side:
                THREE.BackSide

        });


    const atmosphere =
        new THREE.Mesh(
            atmosphereGeometry,
            atmosphereMaterial
        );


    globeGroup.add(
        atmosphere
    );


    // =====================================================
    // Lights
    // =====================================================

    const ambientLight =
        new THREE.AmbientLight(
            "#d9f1ff",
            1.25
        );


    scene.add(
        ambientLight
    );


    const keyLight =
        new THREE.PointLight(
            "#e8f8ff",
            2.0,
            20
        );


    keyLight.position.set(
        4,
        3,
        6
    );


    scene.add(
        keyLight
    );


    const sideLight =
        new THREE.PointLight(
            "#5cc4ff",
            1.3,
            20
        );


    sideLight.position.set(
        -4,
        -1,
        4
    );


    scene.add(
        sideLight
    );


    // =====================================================
    // Initial earth orientation
    // Europe / Africa / Asia area
    // =====================================================

    globeGroup.rotation.y =
        -0.55;

    globeGroup.rotation.x =
        0.10;


    // =====================================================
    // Mouse Interaction
    // =====================================================

    let targetRotX =
        0.10;

    let targetRotZ =
        0;

    let currentRotX =
        0.10;

    let currentRotZ =
        0;


    businessStage.addEventListener(
        "mousemove",
        (event) => {

            const rect =
                businessStage
                    .getBoundingClientRect();


            const normalizedX =
                (
                    event.clientX -
                    rect.left
                ) /
                rect.width *
                2 -
                1;


            const normalizedY =
                -(
                    (
                        event.clientY -
                        rect.top
                    ) /
                    rect.height *
                    2 -
                    1
                );


            targetRotX =
                0.10 +
                normalizedY *
                0.15;


            targetRotZ =
                normalizedX *
                0.10;

        }
    );


    businessStage.addEventListener(
        "mouseleave",
        () => {

            targetRotX =
                0.10;

            targetRotZ =
                0;

        }
    );


    // =====================================================
    // Animation
    // =====================================================

    function animateGlobe() {

        requestAnimationFrame(
            animateGlobe
        );


        currentRotX +=
            (
                targetRotX -
                currentRotX
            ) *
            0.045;


        currentRotZ +=
            (
                targetRotZ -
                currentRotZ
            ) *
            0.045;


        globeGroup.rotation.y +=
            0.0024;


        globeGroup.rotation.x =
            currentRotX;


        globeGroup.rotation.z =
            currentRotZ;


        renderer.render(
            scene,
            camera
        );

    }


    animateGlobe();


    // =====================================================
    // Resize
    // =====================================================

    window.addEventListener(
        "resize",
        () => {

            const newWidth =
                container.clientWidth;

            const newHeight =
                container.clientHeight;


            renderer.setSize(
                newWidth,
                newHeight
            );


            camera.aspect =
                newWidth /
                newHeight;


            camera.updateProjectionMatrix();

        }
    );

}


// =========================================================
